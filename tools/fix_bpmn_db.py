def insert_before_root(body, cells_xml):
    if "</root>" in body:
        return body.replace("</root>", cells_xml + "</root>", 1)
    return body.rstrip() + "\n" + cells_xml


def main():
    xml = read_xml(FILE)
    n_s = n_e = 0
    for page in ("Регистрация", "Арендовать ТС", "Завершить поездку", "Начислить штраф"):
        body = find_page(xml, page)
        cells_xml = ""
        for cid, label, x, y, w, h in STORES.get(page, []):
            cells_xml += (
                f'<mxCell id="{cid}" value="{xml_escape(label)}" style="{STORE_STYLE}" vertex="1" parent="1">'
                f'<mxGeometry x="{x}" y="{y}" width="{w}" height="{h}" as="geometry"/></mxCell>'
            )
            n_s += 1
        for i, (src, tgt) in enumerate(EDGES.get(page, []), start=1):
            eid = f"e-db-{page}-{i}"
            cells_xml += (
                f'<mxCell id="{eid}" style="{DATA_EDGE_STYLE}" edge="1" source="{src}" target="{tgt}" parent="1">'
                '<mxGeometry relative="1" as="geometry"/></mxCell>'
            )
            n_e += 1
        if cells_xml:
            new_body = insert_before_root(body, cells_xml)
            xml = xml.replace(body, new_body, 1)
    with open(FILE, "w", encoding="utf-8") as f:
        f.write(xml)
    print(f"добавлено накопителей: {n_s}")
    print(f"добавлено связей данных: {n_e}")


if __name__ == "__main__":
    main()
