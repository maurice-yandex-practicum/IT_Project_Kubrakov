#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Пакетная замена слов «автомобиль», «машина» и их форм на «ТС»
в файлах проекта с учётом согласования рода (ТС — средний род).

Использование: python3 tools/replace_words.py ФАЙЛ...

Правила замены упорядочены от длинных форм к коротким; скрипт идемпотентен.
"""

import re
import sys

# формы «автомобиль» и «машина» → ТС (все падежи)
BASE = [
    ("автомобилями", "ТС"),
    ("автомобилях", "ТС"),
    ("автомобилей", "ТС"),
    ("автомобилем", "ТС"),
    ("автомобиле", "ТС"),
    ("автомобилю", "ТС"),
    ("автомобиля", "ТС"),
    ("автомобиль", "ТС"),
    ("автомобили", "ТС"),
    ("машинами", "ТС"),
    ("машинах", "ТС"),
    ("машинам", "ТС"),
    ("машиной", "ТС"),
    ("машину", "ТС"),
    ("машине", "ТС"),
    ("машины", "ТС"),
    ("машина", "ТС"),
    ("машин", "ТС"),
]

# формы «транспортное средство» → ТС (кроме паспорта ТС — правка отдельно)
TS_FORMS = [
    ("транспортных средств", "ТС"),
    ("транспортным средствам", "ТС"),
    ("транспортное средство", "ТС"),
    ("транспортного средства", "ТС"),
    ("транспортному средству", "ТС"),
    ("транспортным средством", "ТС"),
]

# согласование рода после замены
AGREEMENT = [
    ("каждый ТС", "каждое ТС"),
    ("этот ТС", "это ТС"),
    ("ТС может быть свободен", "ТС может быть свободно"),
    ("свободен, закреплён за оформляемой арендой, арендован или заблокирован",
     "свободно, закреплено за оформляемой арендой, арендовано или заблокировано"),
    ("свободный ТС", "свободное ТС"),
    ("свободных ТС", "свободных ТС"),
    ("допустимый ТС", "допустимое ТС"),
    ("занятый ТС", "занятое ТС"),
    ("ТС снова доступен", "ТС снова доступно"),
    ("ТС доступен", "ТС доступно"),
    ("ТС заблокирован", "ТС заблокировано"),
    ("ТС арендован", "ТС арендовано"),
    ("ТС закреплён", "ТС закреплено"),
    ("ТС с бензиновым двигателем", "ТС с бензиновым двигателем"),
    ("для электромобиля", "для ТС с электродвигателем"),
    ("электромобиля", "ТС с электродвигателем"),
    ("электромобиль", "ТС с электродвигателем"),
]


def process(text):
    n = 0
    for old, new in BASE + TS_FORMS:
        cnt = text.count(old)
        if cnt:
            text = text.replace(old, new)
            n += cnt
    # правила согласования — только с границами слова, чтобы не задеть «заблокированным» и т. п.
    for old, new in AGREEMENT:
        text, cnt = re.subn(r'\b' + re.escape(old) + r'\b', new, text)
        n += cnt
    return text, n


def main():
    files = sys.argv[1:]
    if not files:
        raise SystemExit("укажите файлы")
    total = 0
    for path in files:
        with open(path, encoding="utf-8") as f:
            text = f.read()
        new_text, n = process(text)
        if n:
            with open(path, "w", encoding="utf-8") as f:
                f.write(new_text)
        print(f"{path}: замен {n}")
        total += n
    print(f"всего замен: {total}")


if __name__ == "__main__":
    main()
